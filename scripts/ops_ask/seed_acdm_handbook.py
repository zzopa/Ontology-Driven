def _upsert_concept_metrics(conn) -> None:
    cur = conn.cursor()
    try:
        cur.execute('SELECT id, code FROM public.ont_concept')
        concept_ids = {row[1]: row[0] for row in cur.fetchall()}
        for concept_code, metric_code, cond_expr, priority in CONCEPT_METRICS:
            cid = concept_ids.get(concept_code)
            if not cid:
                continue
            cur.execute(
                'DELETE FROM public.ont_concept_metric WHERE concept_id = %s AND metric_code = %s',
                (cid, metric_code),
            )
            cur.execute('SELECT COALESCE(MAX(id), 0) + 1 FROM public.ont_concept_metric')
            next_id = int(cur.fetchone()[0])
            import json
            cur.execute(
                'INSERT INTO public.ont_concept_metric (id, concept_id, metric_code, condition_expr, priority) '
                'VALUES (%s, %s, %s, %s::jsonb, %s)',
                (next_id, cid, metric_code, json.dumps(cond_expr, ensure_ascii=False), priority),
            )
        cur.execute(
            "SELECT setval(pg_get_serial_sequence('public.ont_concept_metric', 'id'), "
            "COALESCE((SELECT MAX(id) FROM public.ont_concept_metric), 1), true)"
        )
    finally:
        cur.close()


